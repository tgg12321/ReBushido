/* A chanbara pack is a count of sections, always this, and then where each
 * starts. */
#define PACK_SECTIONS 5
#define PACK_SECTION_NONE -1

/* Which section of a pack each of the packed models is in, from
 * NDATA_PACKED_MODELS on. */
static s16 g_ndata_pack_sections[8] = {
    0,                 /* M301 */
    1,                 /* M302 */
    2,                 /* M303 */
    3,                 /* M304 */
    4,                 /* M305 */
    PACK_SECTION_NONE, /* M300: in neither pack */
    0,                 /* M306 */
    0,                 /* nothing reads it */
};

/* 0 makes ndata_ReadChecked let anything through. Nothing clears it. */
static s32 g_ndata_check_arena_room = 1;
s32 g_ndata_pack_loaded = 0;

/* The archive's two files in the CD file table (CDROM_GROUP_NDATA is the
 * table's first group). */
#define FILE_NDATA_DAT 0
#define FILE_NDATA_INF 1
/* The directory on the disc is 901 entries: two sectors. */
#define NDATA_INF_SECTORS 2

static s32 g_ndata_pack; /* where the loaded chanbara pack is */

/* The entry numbers of the two chanbara packs. Nothing calls these. */
static s32 ndata_GetChanbaraPack0(void) { return NDATA_CHANBARA_PACKS; }

/* Nothing calls it. */
static s32 ndata_GetChanbaraPack1(void) { return NDATA_CHANBARA_PACKS + 1; }

/* Reads a whole entry to `dest_addr` and waits for it. */
static void ndata_Read(s32 id, s32 dest_addr) {
    cdrom_WaitIdle();
    cdrom_StartReadAt(FILE_NDATA_DAT, dest_addr, g_ndata_inf[id].start_sector,
                      g_ndata_inf[id].length_sectors);
    cdrom_WaitIdle();
}

void ndata_ReadModel(s32 model, s32 dest_addr) {
    if (model >= NDATA_FIRST_SHARED_MODEL) {
        model -= NDATA_SHARED_MODEL_STEP;
    }
    if (!ndata_ReadFromPack(model, dest_addr)) {
        ndata_Read(model, dest_addr);
    }
}

void ndata_ReadStage(s32 stage, s32 dest_addr) {
    ndata_Read(stage + NDATA_STAGES, dest_addr);
}

void ndata_ReadWeapons(s32 weapon_set, s32 file, s32 dest_addr) {
    if (!weapon_set) {
        ndata_Read(file + NDATA_WEAPONS, dest_addr);
    } else {
        ndata_Read(file + NDATA_WEAPONS_SET_1, dest_addr);
    }
}

