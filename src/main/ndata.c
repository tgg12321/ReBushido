/* In grayscale mode the caller has already added the step to the gray
 * copies. */
void ndata_ReadTinyModel(s32 tiny_model, s32 dest_addr) {
    ndata_Read(tiny_model + NDATA_TINY_MODELS, dest_addr);
}

/* Reads an entry, first making sure that one bound for the arena fits in
 * what is left of it: if not, the game stops with a message for the
 * development host. Returns the entry's size in bytes. */
s32 ndata_ReadChecked(s32 id, s32 dest_addr) {
    s32 size;
    s32 room;
    s32 offset;

    offset = dest_addr - (s32)arena_GetBase();
    if (offset >= 0 && offset < arena_GetSize()) {
        if (g_ndata_check_arena_room) {
            size = g_ndata_inf[id].length_sectors * NDATA_SECTOR_SIZE;
        } else {
            size = 0;
        }
        room = arena_GetFreeSize();
        if (room < size) {
            printf("Marionation over flow. No.%d (-%dbyte)\n", id, size - room);
            while (1) {
                sys_PollHost();
            }
        }
    } else {
        size = g_ndata_inf[id].length_sectors * NDATA_SECTOR_SIZE;
    }
    ndata_Read(id, dest_addr);
    return size;
}

s32 ndata_GetArenaRoomAfter(s32 id) {
    s32 size = g_ndata_inf[id].length_sectors * NDATA_SECTOR_SIZE;

    return arena_GetFreeSize() - size;
}

void ndata_LoadPack(s32 pack, s32 pack_addr) {
    ndata_Read(pack + NDATA_CHANBARA_PACKS, pack_addr);
    g_ndata_pack = pack_addr;
    g_ndata_pack_loaded = 1;
}

/* Copies a model out of the loaded pack, if it is one of the packed models
 * and the pack has it. Returns 1 if it did. A section runs from its offset,
 * taken down to a whole word, to the next one's. */
static s32 ndata_ReadFromPack(s32 id, s32 dest_addr) {
    s32 *pack;
    u32 start;
    s32 *offset;

    if (!g_ndata_pack_loaded) {
        return 0;
    }
    id -= NDATA_PACKED_MODELS;
    if (id < 0 || id >= NDATA_PACKED_MODEL_COUNT) {
        return 0;
    }
    id = g_ndata_pack_sections[id];
    if (id == PACK_SECTION_NONE) {
        return 0;
    }
    pack = (s32 *)ADDR(g_ndata_pack);
    if (*pack != PACK_SECTIONS) {
        g_ndata_pack_loaded = 0;
        return 0;
    }
    offset = (s32 *)ADDR(id * 4 + (s32)pack + 4);
    start = *offset;
    mem_MoveWords(
        (s32)pack + ((start >> 2) << 2), dest_addr, offset[1] - start);
    return 1;
}

void ndata_InvalidatePack(void) { g_ndata_pack_loaded = 0; }

s32 ndata_IsPackLoaded(void) { return g_ndata_pack_loaded; }

void ndata_StartReadInf(void) {
    cdrom_StartReadAt(FILE_NDATA_INF, (s32)g_ndata_inf, 0, NDATA_INF_SECTORS);
}
