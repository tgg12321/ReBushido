/* LIBC2 CTYPE: toupper and tolower. */
#include "common.h"
#include <psxsdk/libc.h>

char toupper(char ch) {
    char c = ch;
    if ((_ctype_ + 1)[c] & _L) {
        c = ch - 0x20;
    }
    return c;
}

char tolower(char ch) {
    char c = ch;
    if ((_ctype_ + 1)[c] & _U) {
        c = ch + 0x20;
    }
    return c;
}

