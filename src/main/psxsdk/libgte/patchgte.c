/* LIBGTE PATCHGTE: _patch_gte, which InitGeom calls to copy a few
 * instructions over the start of the kernel's exception handler; they follow
 * it here and run to the end of the module. Assembly in Sony's library: the
 * return address is kept in a variable, not on the stack, the BIOS is called
 * through $t2, and the instructions it copies use $k0 and an addi. */
#include "include_asm.h"
#include "common.h"

/* The return address, kept while the BIOS is called. */
s32 _patch_gte_ra;

__asm__(
    ".section .text\n"
    "    .set\tnoat\n"
    "    .set\tnoreorder\n"
    "    .set noat\n"
    "    .set noreorder\n"
    "glabel _patch_gte\n"
    "    lui $at, %hi(_patch_gte_ra)\n"
    "    sw $ra, %lo(_patch_gte_ra)($at)\n"
    "    jal EnterCriticalSection\n"
    "    nop\n"
    "    addiu $t2, $zero, 0xB0\n"
    "    jalr $t2\n"
    "    addiu $t1, $zero, 0x56\n"
    "    lui $t2, %hi(_patch_gte_code)\n"
    "    lui $t1, %hi(CdInit)\n"
    "    lw $v0, 24($v0)\n"
    "    addiu $t2, $t2, %lo(_patch_gte_code)\n"
    "    addiu $t1, $t1, %lo(CdInit)\n"
    ".L8007FF0C:\n"
    "    lw $v1, 0($t2)\n"
    "    addiu $t2, $t2, 0x4\n"
    "    addiu $v0, $v0, 0x4\n"
    "    bne $t2, $t1, .L8007FF0C\n"
    "    sw $v1, -4($v0)\n"
    "    jal FlushCache\n"
    "    nop\n"
    "    jal ExitCriticalSection\n"
    "    nop\n"
    "    lui $ra, %hi(_patch_gte_ra)\n"
    "    lw $ra, %lo(_patch_gte_ra)($ra)\n"
    "    nop\n"
    "    jr $ra\n"
    "    nop\n"
    ".globl _patch_gte_code\n"
    "_patch_gte_code:\n"
    "    nop\n"
    "    nop\n"
    "    addiu $k0, $zero, 0x100\n"
    "    lw $k0, 8($k0)\n"
    "    nop\n"
    "    lw $k0, 0($k0)\n"
    "    nop\n"
    "    addi $k0, $k0, 0x8\n"
    "    sw $at, 4($k0)\n"
    "    sw $v0, 8($k0)\n"
    "    sw $v1, 12($k0)\n"
    "    sw $ra, 124($k0)\n"
    "    .word 0x40026800\n"
    "    nop\n"
    "    .set\treorder\n"
    "    .set\tat\n"
    "    .set reorder\n"
    "    .set at\n");
